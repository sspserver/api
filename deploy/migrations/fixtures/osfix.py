#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate type_os fixture SQL from os.json."""

from __future__ import annotations

import json
import sys
from typing import Any, Iterator


TABLE = "type_os"
COLUMNS = (
    "name, version, description, match_name_exp, match_ua_exp, "
    "match_ver_min_exp, match_ver_max_exp, year_release, year_end_support, "
    "active, parent_id"
)
UPSERT = """ON CONFLICT (name) DO UPDATE SET
    version = EXCLUDED.version,
    description = EXCLUDED.description,
    match_name_exp = EXCLUDED.match_name_exp,
    match_ua_exp = EXCLUDED.match_ua_exp,
    match_ver_min_exp = EXCLUDED.match_ver_min_exp,
    match_ver_max_exp = EXCLUDED.match_ver_max_exp,
    year_release = EXCLUDED.year_release,
    year_end_support = EXCLUDED.year_end_support,
    active = EXCLUDED.active,
    parent_id = EXCLUDED.parent_id,
    updated_at = NOW();"""


def sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def row_sql(entry: dict[str, Any], parent_sql: str) -> str:
    return (
        "  ("
        f"{sql_str(entry['name'])}, "
        f"{sql_str(entry.get('version') or '')}, "
        f"{sql_str(entry.get('description') or '')}, "
        f"{sql_str(entry.get('match_name_exp') or '')}, "
        f"{sql_str(entry.get('match_ua_exp') or '')}, "
        f"{sql_str(entry.get('match_ver_min_exp') or '')}, "
        f"{sql_str(entry.get('match_ver_max_exp') or '')}, "
        f"{int(entry.get('year_release') or 0)}, "
        f"{int(entry.get('year_end_support') or 0)}, "
        f"{sql_str(entry['active'])}, "
        f"{parent_sql}"
        ")"
    )


def insert_block(rows: list[str]) -> Iterator[str]:
    yield f"INSERT INTO {TABLE} ({COLUMNS})"
    yield "VALUES"
    yield ",\n".join(rows)
    yield UPSERT
    yield ""


def generate_sql(json_data: list[dict[str, Any]]) -> Iterator[str]:
    yield "-- Generated by osfix.py from os.json — do not edit by hand."
    yield "BEGIN;"
    yield ""
    yield f"CREATE UNIQUE INDEX IF NOT EXISTS {TABLE}_name_key ON {TABLE} (name);"
    yield ""

    yield "-- Root operating systems"
    yield from insert_block([row_sql(entry, "NULL") for entry in json_data])

    for entry in json_data:
        versions = entry.get("versions") or []
        if not versions:
            continue
        parent_name = entry["name"]
        parent_sql = f"(SELECT id FROM {TABLE} WHERE name = {sql_str(parent_name)} LIMIT 1)"
        yield f"-- Versions of {parent_name}"
        yield from insert_block([row_sql(v, parent_sql) for v in versions])

    yield "COMMIT;"


def main() -> None:
    if len(sys.argv) < 2:
        print("Usage: python osfix.py <os.json> [output.sql]", file=sys.stderr)
        sys.exit(1)

    json_path = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) > 2 else None

    with open(json_path, "r", encoding="utf-8") as f:
        json_data = json.load(f)

    sql = "\n".join(generate_sql(json_data)) + "\n"
    if out_path:
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(sql)
    else:
        sys.stdout.write(sql)


if __name__ == "__main__":
    main()
