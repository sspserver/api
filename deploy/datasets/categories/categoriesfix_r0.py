#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the r0 category fixture from categories.json.

Existing IAB rows are matched by iab_code and kept (same id). Nodes without
an iab_code are inserted by r0_code. Parents are assigned in a later update
because a parent often has no iab_code.
"""

from __future__ import annotations

import json
import sys
from typing import Any, Iterator


def sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def sql_keywords(keywords: list[str]) -> str:
    if not keywords:
        return "ARRAY[]::TEXT[]"
    return "ARRAY[" + ", ".join(sql_str(k) for k in keywords) + "]::TEXT[]"


def opt_str(value: Any, limit: int, field: str, r0_code: str) -> str:
    if value is None or value == "":
        return "NULL"
    text = str(value)
    if len(text) > limit:
        raise SystemExit(f"{r0_code}: {field} length {len(text)} exceeds {limit}")
    return sql_str(text)


def walk(nodes: list[dict[str, Any]], parent_r0: str | None) -> Iterator[dict[str, Any]]:
    for index, node in enumerate(nodes, start=1):
        r0_code = (node.get("r0_code") or "").strip()
        if not r0_code:
            raise SystemExit(f"category {node.get('name')!r} has no r0_code")
        r0_parent = node.get("r0_parent") or None
        if r0_parent == "":
            r0_parent = None
        if r0_parent != parent_r0:
            raise SystemExit(
                f"{r0_code}: r0_parent {r0_parent!r} does not match tree parent {parent_r0!r}"
            )
        name = node.get("name") or ""
        if not name or len(name) > 255:
            raise SystemExit(f"{r0_code}: name length {len(name)} is empty or exceeds 255")
        if len(r0_code) > 128:
            raise SystemExit(f"{r0_code}: r0_code length exceeds 128")
        position = int(node["position"]) if node.get("position") is not None else index
        iab = (node.get("iab_code") or "").strip() or None
        yield {
            "name": name,
            "description": node["description"] if "description" in node else None,
            "description_set": "description" in node,
            "iab_code": iab,
            "keywords": node.get("keywords") if "keywords" in node else None,
            "keywords_set": "keywords" in node,
            "r0_code": r0_code,
            "c3_1_code": node.get("c3_1_code") or None,
            "cattax": node.get("cattax_id") or None,
            "r0_parent": r0_parent,
            "position": position,
        }
        yield from walk(node.get("childrens") or [], r0_code)


def value_row(node: dict[str, Any]) -> str:
    description = node["description"]
    if node["description_set"] and description is None:
        description = ""
    keywords = node["keywords"] or []
    return (
        "("
        f"{sql_str(node['name'])}, "
        f"{sql_str(description) if node['description_set'] else 'NULL'}, "
        f"{'TRUE' if node['description_set'] else 'FALSE'}, "
        f"{sql_str(node['iab_code']) if node['iab_code'] else 'NULL'}, "
        f"{sql_keywords(keywords) if node['keywords_set'] else 'NULL'}, "
        f"{'TRUE' if node['keywords_set'] else 'FALSE'}, "
        f"{sql_str(node['r0_code'])}, "
        f"{opt_str(node['c3_1_code'], 64, 'c3_1_code', node['r0_code'])}, "
        f"{opt_str(node['cattax'], 32, 'cattax', node['r0_code'])}, "
        f"{sql_str(node['r0_parent']) if node['r0_parent'] else 'NULL'}, "
        f"{node['position']}"
        ")"
    )


def generate_sql(nodes: list[dict[str, Any]]) -> str:
    rows = list(walk(nodes, None))
    seen_r0: set[str] = set()
    seen_iab: set[str] = set()
    for node in rows:
        if node["r0_code"] in seen_r0:
            raise SystemExit(f"duplicate r0_code {node['r0_code']}")
        seen_r0.add(node["r0_code"])
        if node["iab_code"]:
            if node["iab_code"] in seen_iab:
                raise SystemExit(f"duplicate iab_code {node['iab_code']}")
            seen_iab.add(node["iab_code"])
    parents = {node["r0_parent"] for node in rows if node["r0_parent"]}
    missing_parents = sorted(parents - seen_r0)
    if missing_parents:
        raise SystemExit("missing r0 parents: " + ", ".join(missing_parents[:10]))

    lines = [
        "-- Generated by categoriesfix_r0.py from categories.json — do not edit by hand.",
        "BEGIN;",
        "",
        "CREATE TEMP TABLE category_r0_load (",
        "    name            TEXT NOT NULL,",
        "    description     TEXT,",
        "    description_set BOOLEAN NOT NULL,",
        "    iab_code        VARCHAR(255),",
        "    keywords        TEXT[],",
        "    keywords_set    BOOLEAN NOT NULL,",
        "    r0_code         VARCHAR(128) NOT NULL,",
        "    c3_1_code       VARCHAR(64),",
        "    cattax          VARCHAR(32),",
        "    r0_parent       VARCHAR(128),",
        "    position        BIGINT NOT NULL",
        ");",
        "",
        "INSERT INTO category_r0_load (",
        "    name, description, description_set, iab_code, keywords, keywords_set,",
        "    r0_code, c3_1_code, cattax, r0_parent, position",
        ")",
        "VALUES",
        ",\n".join(value_row(node) for node in rows) + ";",
        "",
        "-- Keep one existing row per iab_code (lowest id). Do not move parent_id yet.",
        "UPDATE adv_category AS c",
        "SET name = src.name,",
        "    description = CASE",
        "        WHEN src.description_set THEN COALESCE(src.description, '')",
        "        ELSE c.description",
        "    END,",
        "    keywords = CASE",
        "        WHEN src.keywords_set THEN COALESCE(src.keywords, '{}'::TEXT[])",
        "        ELSE c.keywords",
        "    END,",
        "    r0_code = src.r0_code,",
        "    c3_1_code = src.c3_1_code,",
        "    cattax = src.cattax,",
        "    updated_at = NOW()",
        "FROM category_r0_load AS src",
        "WHERE src.iab_code IS NOT NULL",
        "  AND c.id = (",
        "      SELECT MIN(id) FROM adv_category",
        "      WHERE iab_code = src.iab_code",
        "  );",
        "",
        "INSERT INTO adv_category (",
        "    name, description, iab_code, keywords, parent_id, position,",
        "    r0_code, c3_1_code, cattax",
        ")",
        "SELECT",
        "    src.name,",
        "    COALESCE(src.description, ''),",
        "    src.iab_code,",
        "    CASE WHEN src.keywords_set THEN COALESCE(src.keywords, '{}'::TEXT[]) ELSE '{}'::TEXT[] END,",
        "    NULL,",
        "    src.position,",
        "    src.r0_code,",
        "    src.c3_1_code,",
        "    src.cattax",
        "FROM category_r0_load AS src",
        "WHERE src.iab_code IS NOT NULL",
        "  AND NOT EXISTS (",
        "      SELECT 1 FROM adv_category AS c WHERE c.iab_code = src.iab_code",
        "  );",
        "",
        "INSERT INTO adv_category (",
        "    name, description, iab_code, keywords, parent_id, position,",
        "    r0_code, c3_1_code, cattax",
        ")",
        "SELECT",
        "    src.name,",
        "    COALESCE(src.description, ''),",
        "    NULL,",
        "    CASE WHEN src.keywords_set THEN COALESCE(src.keywords, '{}'::TEXT[]) ELSE '{}'::TEXT[] END,",
        "    NULL,",
        "    src.position,",
        "    src.r0_code,",
        "    src.c3_1_code,",
        "    src.cattax",
        "FROM category_r0_load AS src",
        "WHERE src.iab_code IS NULL",
        "ON CONFLICT (r0_code) WHERE r0_code IS NOT NULL DO NOTHING;",
        "",
        "DO $$",
        "BEGIN",
        "    IF EXISTS (",
        "        SELECT 1",
        "        FROM category_r0_load AS src",
        "        WHERE src.r0_parent IS NOT NULL",
        "          AND NOT EXISTS (",
        "              SELECT 1 FROM adv_category AS p WHERE p.r0_code = src.r0_parent",
        "          )",
        "    ) THEN",
        "        RAISE EXCEPTION 'category r0_parent does not match an adv_category row';",
        "    END IF;",
        "END $$;",
        "",
        "UPDATE adv_category AS c",
        "SET name = src.name,",
        "    description = CASE",
        "        WHEN src.description_set THEN COALESCE(src.description, '')",
        "        ELSE c.description",
        "    END,",
        "    keywords = CASE",
        "        WHEN src.keywords_set THEN COALESCE(src.keywords, '{}'::TEXT[])",
        "        ELSE c.keywords",
        "    END,",
        "    c3_1_code = src.c3_1_code,",
        "    cattax = src.cattax,",
        "    parent_id = p.id,",
        "    position = src.position,",
        "    updated_at = NOW()",
        "FROM category_r0_load AS src",
        "LEFT JOIN adv_category AS p ON p.r0_code = src.r0_parent",
        "WHERE c.r0_code = src.r0_code;",
        "",
        "-- Rows outside the tree, including extra copies of the same iab_code.",
        "UPDATE adv_category",
        "SET r0_code = 'legacy.' || id::text,",
        "    updated_at = NOW()",
        "WHERE r0_code IS NULL OR r0_code = '';",
        "",
        "DO $$",
        "BEGIN",
        "    IF EXISTS (SELECT 1 FROM adv_category WHERE r0_code IS NULL OR r0_code = '') THEN",
        "        RAISE EXCEPTION 'adv_category rows without r0_code remain';",
        "    END IF;",
        "END $$;",
        "",
        "ALTER TABLE adv_category",
        "    ALTER COLUMN r0_code SET NOT NULL;",
        "",
        "COMMIT;",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 3:
        print(
            "Usage: python categoriesfix_r0.py <categories.json> <output.sql>",
            file=sys.stderr,
        )
        sys.exit(1)
    with open(sys.argv[1], encoding="utf-8") as handle:
        payload = json.load(handle)
    categories = payload["categories"] if isinstance(payload, dict) else payload
    sql = generate_sql(categories)
    with open(sys.argv[2], "w", encoding="utf-8") as handle:
        handle.write(sql)


if __name__ == "__main__":
    main()
